// One-off import step 2: turns output/events-ready-to-import.csv (from scripts/process-event-posters.mjs) into a
// reviewed SQL script that inserts only the events that are not in public.events yet. This script never writes to
// the database: the generated SQL is run by hand after the plan has been reviewed.
//
//   node --env-file=.env scripts/build-events-import-sql.mjs                validate the CSV, write events-import.sql
//   node --env-file=.env scripts/build-events-import-sql.mjs --inspect-db   also read the live table (READ ONLY
//                                                                           transaction over DATABASE_URL) and write
//                                                                           events-db-inspection.json and
//                                                                           events-insert-plan.json
//   options: --csv <file>  --out <dir>
//
// Without the CSV (only a dry run so far), --inspect-db still inspects the table and writes a preliminary plan from
// output/events-processing-report.json (titles and categories only: no poster URLs exist yet), but no SQL.
//
// Why SQL and not the Supabase CSV importer: the importer cannot skip titles that already exist. The generated SQL
// stages the rows in a temp table and inserts with NOT EXISTS on lower(btrim(title)), under a lock that blocks
// concurrent inserts, so it never duplicates, updates or deletes an existing event and is safe to run twice.
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { CSV_COLUMNS, EVENTS_FOLDER, TEXT_LIMITS, normalizeTitle, parseCsv } from './process-event-posters.mjs';

// Values allowed by events_category_check in supabase/schema.sql (this import only produces the first three).
export const DB_CATEGORIES = ['flagship events', 'standout events', 'main events', 'dts events', 'fun events'];
const POSTER_RE = /^https:\/\/[^\s"'<>]+$/i; // events_poster_url_check
const BROCHURE_RE = /^https?:\/\/([a-z0-9-]+\.)*(drive|docs)\.google\.com\/.+/i; // events_brochure_url_check

/** Checks every CSV row against the table's constraints and the admin API rules. Returns a list of problems. */
export function validateRows(header, records, { urlEndpoint } = {}) {
  const errors = [];
  if (header.join(',') !== CSV_COLUMNS.join(',')) errors.push(`CSV columns must be exactly ${CSV_COLUMNS.join(', ')} (found ${header.join(', ')})`);
  const seen = new Map();
  const posterPrefix = urlEndpoint ? `${urlEndpoint.replace(/\/+$/, '')}${EVENTS_FOLDER}/` : null;
  records.forEach((r, i) => {
    const at = `CSV line ${i + 2} (${r.title || 'no title'})`;
    for (const c of CSV_COLUMNS) if (String(r[c]).includes('\0')) errors.push(`${at}: ${c} contains a NUL character`);
    if (!r.title.trim()) errors.push(`${at}: empty title`);
    if (r.title.length > TEXT_LIMITS.title) errors.push(`${at}: title longer than ${TEXT_LIMITS.title}`);
    if (!r.description.trim()) errors.push(`${at}: empty description`);
    if (r.description.length > TEXT_LIMITS.description) errors.push(`${at}: description longer than ${TEXT_LIMITS.description}`);
    if (!DB_CATEGORIES.includes(r.category)) errors.push(`${at}: category "${r.category}" is not allowed by events_category_check`);
    if (!POSTER_RE.test(r.poster_url)) errors.push(`${at}: poster_url fails events_poster_url_check`);
    if (posterPrefix && !r.poster_url.startsWith(posterPrefix)) errors.push(`${at}: poster_url is not under ${posterPrefix}`);
    if (r.brochure_url && !BROCHURE_RE.test(r.brochure_url)) errors.push(`${at}: brochure_url fails events_brochure_url_check`);
    if (r.brochure_url.length > TEXT_LIMITS.brochure_url) errors.push(`${at}: brochure_url longer than ${TEXT_LIMITS.brochure_url}`);
    const key = normalizeTitle(r.title);
    if (seen.has(key)) errors.push(`${at}: same title as CSV line ${seen.get(key)}`);
    else seen.set(key, i + 2);
  });
  return errors;
}

const sqlText = (v) => (v === null || v === undefined || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

/** The import transaction. Rows keep CSV order; created_at is staggered so the site (newest first) shows that order. */
export function buildSql(records, { source, generatedAt }) {
  const values = records.map((r, i) =>
    `  (${i + 1}, ${sqlText(r.title.trim())}, ${sqlText(r.description)}, ${sqlText(r.poster_url)}, ${sqlText(r.brochure_url)}, ${sqlText(r.category)})`,
  ).join(',\n');
  return `-- Innovision 2026 event import. Generated by scripts/build-events-import-sql.mjs at ${generatedAt}
-- from ${source} (${records.length} rows).
--
-- Inserts only events whose title (trimmed, case-insensitive) is not in public.events yet.
-- Never updates or deletes an existing row; running it twice inserts nothing the second time.
-- Run once, in the Supabase SQL Editor or with: psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f output/events-import.sql
-- created_by / updated_by stay NULL: the authorship trigger only stamps requests made by a signed-in staff user.

BEGIN;
SET LOCAL standard_conforming_strings = on;

-- Blocks other inserts/updates/deletes on events until COMMIT, so the duplicate check below cannot race.
-- Reads (the public site) are not blocked.
LOCK TABLE public.events IN SHARE ROW EXCLUSIVE MODE;

CREATE TEMP TABLE events_import_staging (
  ord INT PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  poster_url TEXT NOT NULL,
  brochure_url TEXT,
  category TEXT NOT NULL
) ON COMMIT DROP;

INSERT INTO events_import_staging (ord, title, description, poster_url, brochure_url, category) VALUES
${values};

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM events_import_staging GROUP BY lower(btrim(title)) HAVING count(*) > 1) THEN
    RAISE EXCEPTION 'events_import_staging has duplicate titles: nothing imported';
  END IF;
END $$;

-- Sheet order on the site: the first row gets the newest created_at (1 ms apart).
INSERT INTO public.events (title, description, poster_url, brochure_url, category, created_at, updated_at)
SELECT s.title, s.description, s.poster_url, s.brochure_url, s.category,
       timezone('utc'::text, now()) - s.ord * interval '1 millisecond',
       timezone('utc'::text, now()) - s.ord * interval '1 millisecond'
FROM events_import_staging s
WHERE NOT EXISTS (
  SELECT 1 FROM public.events e WHERE lower(btrim(e.title)) = lower(btrim(s.title))
)
ORDER BY s.ord;

-- What happened, per row (the last result shown by the SQL Editor).
SELECT s.ord, s.title, s.category,
       CASE WHEN e.created_at = timezone('utc'::text, now()) - s.ord * interval '1 millisecond'
            THEN 'inserted' ELSE 'skipped: title already existed' END AS result,
       e.id AS event_id
FROM events_import_staging s
JOIN public.events e ON lower(btrim(e.title)) = lower(btrim(s.title))
ORDER BY s.ord;

COMMIT;
`;
}

/* ------------------------------------------------ database (read only) ------------------------------------------------ */

async function inspectDatabase(databaseUrl) {
  const { default: pg } = await import('pg');
  const client = new pg.Client({ connectionString: databaseUrl, application_name: 'innovision-event-import-inspect' });
  await client.connect();
  try {
    await client.query('BEGIN READ ONLY');
    const q = async (sql) => (await client.query(sql)).rows;
    const out = {
      inspectedAt: new Date().toISOString(),
      serverVersion: (await q('SHOW server_version'))[0].server_version,
      columns: await q(`SELECT column_name, data_type, is_nullable, column_default
                        FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'events'
                        ORDER BY ordinal_position`),
      constraints: await q(`SELECT conname AS name, contype AS type, convalidated AS validated, pg_get_constraintdef(oid) AS definition
                            FROM pg_constraint WHERE conrelid = 'public.events'::regclass ORDER BY conname`),
      indexes: await q(`SELECT indexname AS name, indexdef AS definition FROM pg_indexes
                        WHERE schemaname = 'public' AND tablename = 'events' ORDER BY indexname`),
      triggers: await q(`SELECT tgname AS name, pg_get_triggerdef(oid) AS definition FROM pg_trigger
                         WHERE tgrelid = 'public.events'::regclass AND NOT tgisinternal ORDER BY tgname`),
      rlsEnabled: (await q(`SELECT relrowsecurity FROM pg_class WHERE oid = 'public.events'::regclass`))[0].relrowsecurity,
      existingEvents: await q(`SELECT id, title, category, created_by, created_at FROM public.events ORDER BY created_at`),
      existingDuplicateTitles: await q(`SELECT lower(btrim(title)) AS title_key, count(*)::int AS rows FROM public.events
                                        GROUP BY 1 HAVING count(*) > 1 ORDER BY 1`),
    };
    out.uniqueOnTitle = out.indexes.filter((i) => /UNIQUE/i.test(i.definition) && /title/i.test(i.definition));
    return out;
  } finally {
    await client.query('ROLLBACK').catch(() => {});
    await client.end();
  }
}

/** Which candidates the SQL will insert and which it will skip, given the live titles. */
export function insertPlan(candidates, existingEvents) {
  const existing = new Map(existingEvents.map((e) => [normalizeTitle(e.title), e]));
  const plan = candidates.map((c, i) => {
    const hit = existing.get(normalizeTitle(c.title));
    return hit
      ? { ord: i + 1, title: c.title, category: c.category, action: 'skip', reason: 'title already in public.events', existingId: hit.id, existingTitle: hit.title }
      : { ord: i + 1, title: c.title, category: c.category, action: 'insert' };
  });
  return { insert: plan.filter((p) => p.action === 'insert').length, skip: plan.filter((p) => p.action === 'skip').length, rows: plan };
}

/* ------------------------------------------------ run ------------------------------------------------ */

function parseArgs(argv) {
  const opts = { csv: join('output', 'events-ready-to-import.csv'), out: 'output', inspectDb: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--inspect-db') opts.inspectDb = true;
    else if (a === '--csv') opts.csv = argv[++i];
    else if (a === '--out') opts.out = argv[++i];
    else throw new Error(`unknown argument "${a}"`);
  }
  if (!opts.csv || !opts.out) throw new Error('--csv and --out need a value');
  return opts;
}

async function main(argv) {
  const opts = parseArgs(argv);
  const outDir = resolve(opts.out);
  const csvPath = resolve(opts.csv);
  const generatedAt = new Date().toISOString();

  let candidates = null;
  let preliminary = false;
  if (existsSync(csvPath)) {
    const { header, records } = parseCsv(await readFile(csvPath, 'utf8'));
    const errors = validateRows(header, records, { urlEndpoint: process.env.IMAGEKIT_URL_ENDPOINT });
    if (errors.length) throw new Error(`CSV is not importable:\n  ${errors.join('\n  ')}`);
    if (!records.length) throw new Error('CSV has no rows');
    candidates = records;
    await writeFile(join(outDir, 'events-import.sql'), buildSql(records, { source: opts.csv.replace(/\\/g, '/'), generatedAt }));
    console.error(`wrote ${join(opts.out, 'events-import.sql')} (${records.length} rows)`);
  } else {
    const reportPath = join(outDir, 'events-processing-report.json');
    if (!opts.inspectDb || !existsSync(reportPath)) throw new Error(`${opts.csv} not found: run scripts/process-event-posters.mjs first`);
    const report = JSON.parse(await readFile(reportPath, 'utf8'));
    candidates = report.events.filter((e) => e.status === 'converted' || e.status === 'ready').map((e) => ({ title: e.title, category: e.category }));
    preliminary = true;
    console.error(`${opts.csv} not found: preliminary plan from the ${report.mode} report, no SQL written`);
  }

  if (!opts.inspectDb) return;
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is not set (run with node --env-file=.env)');
  const inspection = await inspectDatabase(process.env.DATABASE_URL);
  await writeFile(join(outDir, 'events-db-inspection.json'), JSON.stringify(inspection, null, 2) + '\n');
  const plan = { generatedAt, preliminary, source: preliminary ? 'events-processing-report.json' : opts.csv, ...insertPlan(candidates, inspection.existingEvents) };
  await writeFile(join(outDir, 'events-insert-plan.json'), JSON.stringify(plan, null, 2) + '\n');
  console.log(JSON.stringify({
    existingEvents: inspection.existingEvents.length,
    uniqueIndexOnTitle: inspection.uniqueOnTitle.map((i) => i.name),
    preliminary,
    insert: plan.insert,
    skip: plan.rows.filter((r) => r.action === 'skip').map((r) => `${r.title} (exists as "${r.existingTitle}")`),
  }, null, 2));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2)).catch((err) => {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  });
}
